local budget = require("kf/budget")

describe("budget.effective", function()
    it("uses the configured budget when the window is large (device defaults)", function()
        assert_eq(budget.effective(25, 60, 5), 25)
    end)
    it("is capped by window - margin", function()
        assert_eq(budget.effective(25, 20, 5), 15)
    end)
    it("returns nil when the window is unknown", function()
        assert_nil(budget.effective(25, nil, 5))
    end)
    it("returns nil when too little time is left to be useful", function()
        assert_nil(budget.effective(25, 7, 5))
        assert_nil(budget.effective(25, 4, 5))
    end)
    it("clamps silly budgets", function()
        assert_eq(budget.effective(0, 60, 5), budget.MIN_BUDGET)
        assert_eq(budget.effective(999, 120, 5), budget.MAX_BUDGET)
    end)
    it("falls back to defaults for missing budget / margin", function()
        assert_eq(budget.effective(nil, 60, nil), budget.DEFAULT_BUDGET)
    end)
end)
