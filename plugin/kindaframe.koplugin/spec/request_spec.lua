local req = require("kf/request")

describe("request.build_url", function()
    it("adds w, h, batt", function()
        assert_eq(req.build_url("http://192.168.1.50:8787/frame.png", 1072, 1448, 84),
            "http://192.168.1.50:8787/frame.png?w=1072&h=1448&batt=84")
    end)
    it("keeps an existing query and clamps battery", function()
        assert_eq(req.build_url("http://h/frame.png?x=1", 10, 20, 140), "http://h/frame.png?x=1&w=10&h=20&batt=100")
    end)
    it("adds a landscape orientation, omits portrait and ignores junk", function()
        assert_eq(req.build_url("http://h/f.png", 10, 20, 50, "left"), "http://h/f.png?w=10&h=20&batt=50&orient=left")
        assert_eq(req.build_url("http://h/f.png", 10, 20, 50, "right"), "http://h/f.png?w=10&h=20&batt=50&orient=right")
        assert_eq(req.build_url("http://h/f.png", 10, 20, 50, "portrait"), "http://h/f.png?w=10&h=20&batt=50")
        assert_eq(req.build_url("http://h/f.png", 10, 20, 50, "sideways"), "http://h/f.png?w=10&h=20&batt=50")
    end)
    it("omits batt when unknown", function()
        assert_eq(req.build_url("http://h/f.png", 10, 20, nil), "http://h/f.png?w=10&h=20")
    end)
end)

describe("request.valid_base", function()
    it("accepts plain http only", function()
        assert_true(req.valid_base("http://192.168.1.50:8787/frame.png"))
        assert_false(req.valid_base("https://example.org/frame.png"))
        assert_false(req.valid_base(""))
        assert_false(req.valid_base(nil))
    end)
end)

describe("request result protocol", function()
    it("round-trips HTTP codes", function()
        assert_eq(req.classify(req.encode_result(200)), "ok")
        assert_eq(req.classify(req.encode_result(503)), "http_503")
    end)
    it("classifies errors", function()
        assert_eq((req.classify(req.encode_result(nil, "timeout"))), "timeout")
        assert_eq((req.classify(req.encode_result(nil, "connection refused"))), "unreachable")
        assert_eq((req.classify("")), "unreachable")
        assert_eq((req.classify(nil)), "unreachable")
    end)
    it("keeps the error on one line", function()
        assert_eq(req.encode_result(nil, "a\nb"), "ERR a b")
    end)
end)
